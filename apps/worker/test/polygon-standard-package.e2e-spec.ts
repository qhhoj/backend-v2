import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { getConnectionToken, getModelToken } from '@nestjs/mongoose';
import type { Job } from 'bullmq';
import type { Connection, Model } from 'mongoose';
import { waitUntil } from '@libs/common/testing';
import { newId, PolygonSyncRun, TestGeneration } from '@libs/database';
import { generationBucket } from '@libs/judging';
import type { GenerationPlan } from '@libs/judging';
import {
  listZipEntries,
  POLYGON_ERROR_PREFIX,
  POLYGON_FETCH,
} from '@libs/problems';
import type { ImportProgress, PolygonImportJob } from '@libs/problems';
import { buildZip, FakePolygon } from '@libs/problems/testing';
import { PandocService } from '../src/jobs/polygon-import/pandoc.service';
import { PolygonImportProcessor } from '../src/jobs/polygon-import/polygon-import.processor';
import { buildPolygonPackage, properties } from './polygon-fixtures';
import type { PolygonFixture } from './polygon-fixtures';
import { setupWorkerTest } from './setup';
import type { WorkerTest } from './setup';

const fakePandoc = {
  assertAvailable: () => Promise.resolve(),
  texToMarkdown: (tex: string) => Promise.resolve(tex),
};
const POLYGON_ID = 7;
const FIXTURE: PolygonFixture = {
  tests: [
    { input: '', answer: '', group: 'g1' },
    { input: '', answer: '', group: 'g1' },
    { input: '5 6', answer: '', group: 'g1' },
  ],
  groups: [{ name: 'g1', points: 100, policy: 'complete-group' }],
  checker: { path: 'files/check.cpp' },
  statements: [
    {
      language: 'english',
      name: 'Sum',
      properties: properties({ legend: 'Add.' }),
    },
  ],
  solution: {
    path: 'solutions/main.cpp',
    type: 'cpp.g++17',
    code: 'int main() {}',
  },
  files: {
    'files/gen.cpp': '// generator',
    'files/testlib.h': '// testlib',
    'files/olymp.sty': 'not a header',
  },
  omitEntries: [
    'tests/01',
    'tests/01.a',
    'tests/02',
    'tests/02.a',
    'tests/03.a',
  ],
};

/** Tests 1 and 2 become generated by `gen`; the package has the generator, a header, and no answers anywhere. */
const toStandardXml = (xml: string): string =>
  xml
    .replace('<test method="manual"', '<test cmd="gen 1" method="generated"')
    .replace('<test method="manual"', '<test cmd="gen 2" method="generated"')
    .replace(
      '<assets>',
      '<files><resources><file path="files/testlib.h" type="h.g++"/><file path="files/olymp.sty"/></resources><executables><executable><source path="files/gen.cpp" type="cpp.g++17"/></executable></executables></files><assets>',
    );
const standardPackage = (overrides: Partial<PolygonFixture> = {}): Buffer =>
  buildPolygonPackage({
    ...FIXTURE,
    transformXml: toStandardXml,
    ...overrides,
  });

describe('Polygon standard package import', () => {
  let worker: WorkerTest;
  let processor: PolygonImportProcessor;
  let generations: Model<TestGeneration>;
  let connection: Connection;
  let runs: Model<PolygonSyncRun>;
  let requesterId: string;
  const polygon = new FakePolygon();

  const job = (code: string): Job<PolygonImportJob> => {
    const progress: ImportProgress[] = [];
    const data: PolygonImportJob = {
      requesterId,
      code,
      mode: 'create',
      groupId: undefined,
      typeIds: [],
      points: 900,
      authors: [requesterId],
      isFullMarkup: false,
      mainStatementLanguage: 'english',
      statementLanguages: {},
      tutorialLanguage: null,
      ignoreZeroPointBatches: false,
      ignoreZeroPointCases: false,
      appendMainSolution: false,
      maxCases: 300,
      polygon: {
        problemId: POLYGON_ID,
        name: 'sum',
        owner: 'setter',
        revision: 3,
        packageId: 70,
        packageType: 'standard',
        purpose: 'link',
        autoSync: false,
      },
    };
    const queued = {
      id: newId(),
      data,
      updateProgress: (value: ImportProgress) => {
        progress.push(value);
        return Promise.resolve();
      },
      updateData: (value: PolygonImportJob) => {
        queued.data = value;
        return Promise.resolve();
      },
      progress,
    };
    return queued as unknown as Job<PolygonImportJob> & {
      progress: ImportProgress[];
    };
  };

  /** What a judge and the bridge do: take the queued row, then finish it with `outcome`. */
  const actAsJudge = async (
    outcome: (
      plan: GenerationPlan,
      bundleFileId: unknown,
    ) => Promise<Partial<TestGeneration>>,
  ): Promise<{ plan: GenerationPlan; bundleFileId: unknown }> => {
    let row: TestGeneration | null = null;
    await waitUntil(async () => {
      row = await generations.findOne({ status: 'queued' }).lean();
      return row !== null;
    });
    const { _id, plan, bundleFileId } = row as unknown as TestGeneration;
    await generations.updateOne(
      { _id: _id as never },
      { $set: await outcome(plan as unknown as GenerationPlan, bundleFileId) },
    );
    return { plan: plan as unknown as GenerationPlan, bundleFileId };
  };

  const uploadResult = async (
    entries: Array<{ name: string; content: string }>,
  ) => {
    const upload = generationBucket(connection).openUploadStream('result.zip');
    await new Promise<void>((resolve, reject) =>
      upload.end(buildZip(entries), (error?: Error | null) =>
        error ? reject(error) : resolve(),
      ),
    );
    return upload.id;
  };

  const bundleEntries = async (bundleFileId: unknown): Promise<string[]> => {
    const directory = mkdtempSync(join(tmpdir(), 'bundle-'));
    try {
      const path = join(directory, 'bundle.zip');
      const chunks: Buffer[] = [];
      for await (const chunk of generationBucket(connection).openDownloadStream(
        bundleFileId as never,
      ))
        chunks.push(chunk as Buffer);
      writeFileSync(path, Buffer.concat(chunks));
      return (await listZipEntries(path)).sort();
    } finally {
      rmSync(directory, { recursive: true, force: true });
    }
  };

  beforeAll(async () => {
    worker = await setupWorkerTest({
      overrides: [
        { provide: PandocService, useValue: fakePandoc },
        { provide: POLYGON_FETCH, useValue: polygon.fetch },
      ],
    });
    processor = worker.module.get(PolygonImportProcessor);
    generations = worker.module.get(getModelToken(TestGeneration.name));
    runs = worker.module.get(getModelToken(PolygonSyncRun.name));
    connection = worker.module.get(getConnectionToken());
    await worker.setSetting('polygon.apiKey', 'KEY');
    await worker.setSetting('polygon.apiSecret', 'SECRET');
    await worker.problemGroups.create({ name: 'Uncategorized', fullName: 'U' });
    // A create that names no type takes the oldest one.
    await worker.problemTypes.create({ name: 'misc', fullName: 'Misc' });
    await worker.languages.create({
      key: 'CPP17',
      name: 'C++17',
      commonName: 'C++',
      ace: 'c_cpp',
      pygments: 'cpp',
      extension: 'cpp',
      includeInProblem: true,
    });
    requesterId = (
      await worker.users.create({ username: 'setter', password: '!' })
    )._id;
  });
  beforeEach(() => polygon.reset());
  afterAll(() => worker.teardown());

  it('plans, queues the generation, and imports the judge result as tests.zip, then cleans up', async () => {
    polygon.reply('problem.package', { zip: standardPackage() });
    const queued = job('stdok');
    let bundled: string[] = [];
    const judge = actAsJudge(async (_plan, bundleFileId) => {
      bundled = await bundleEntries(bundleFileId);
      return {
        status: 'done',
        resultFileId: await uploadResult([
          { name: '01.inp', content: '1' },
          { name: '01.out', content: '1' },
          { name: '02.inp', content: '2' },
          { name: '02.out', content: '2' },
          { name: '03.inp', content: '5 6' },
          { name: '03.out', content: '11' },
        ]),
      };
    });
    const result = await processor.process(queued);
    const { plan } = await judge;

    expect(polygon.callsOf('problem.package')[0].params).toMatchObject({
      type: 'standard',
    });
    expect(
      plan.tests.map(({ generator, manualPath }) => [generator, manualPath]),
    ).toEqual([
      ['gen', ''],
      ['gen', ''],
      ['', 'tests/03'],
    ]);
    expect(bundled).toEqual([
      'files/gen.cpp',
      'files/testlib.h',
      'solutions/main.cpp',
      'solutions/testlib.h',
      'tests/03',
    ]);
    const steps = (
      queued as unknown as { progress: ImportProgress[] }
    ).progress.map(({ step }) => step);
    expect([...new Set(steps)]).toEqual([
      'downloading',
      'statements',
      'generating',
      'tests',
    ]);
    const archive = join(worker.problemDataRoot, 'stdok', 'tests.zip');
    expect((await listZipEntries(archive)).sort()).toEqual([
      '01.inp',
      '01.out',
      '02.inp',
      '02.out',
      '03.inp',
      '03.out',
    ]);
    expect(result).toMatchObject({ code: 'stdok' });
    expect(await runs.findOne({ code: 'stdok' }).lean()).toMatchObject({
      packageType: 'standard',
      result: 'ok',
    });
    expect(await generations.countDocuments()).toBe(0);
    expect(await generationBucket(connection).find({}).toArray()).toEqual([]);
  });

  it('shows the judge failure and stops at the generating step', async () => {
    polygon.reply('problem.package', { zip: standardPackage() });
    const queued = job('stdbad');
    const judge = actAsJudge(() =>
      Promise.resolve({
        status: 'failed',
        failure: {
          stage: 'VALIDATE',
          kind: 'REJECTED',
          program: 'validator',
          testIndex: 2,
          detail: 'n is 0',
        },
      }),
    );
    await expect(processor.process(queued)).rejects.toThrow(
      `${POLYGON_ERROR_PREFIX}test 2 (group g1) is rejected by the validator: n is 0`,
    );
    await judge;
    expect(queued.data.failedStep).toBe('generating');
    expect(await worker.problems.countDocuments({ code: 'stdbad' })).toBe(0);
    expect(await generations.countDocuments()).toBe(0);
    expect(await generationBucket(connection).find({}).toArray()).toEqual([]);
  });

  it('refuses a result zip that lacks a promised test', async () => {
    polygon.reply('problem.package', { zip: standardPackage() });
    const judge = actAsJudge(async () => ({
      status: 'done',
      resultFileId: await uploadResult([{ name: '01.inp', content: '1' }]),
    }));
    await expect(processor.process(job('stdshort'))).rejects.toThrow(
      'the generated tests lack 01.out',
    );
    await judge;
    expect(await generations.countDocuments()).toBe(0);
  });

  it('refuses a standard package it cannot plan before queuing anything', async () => {
    polygon.reply('problem.package', {
      zip: standardPackage({ solution: null }),
    });
    await expect(processor.process(job('stdplan'))).rejects.toThrow(
      /no main solution|not found|generator/,
    );
    expect(await generations.countDocuments()).toBe(0);
  });
});
