#!/usr/bin/env bash
# deploy/nginx/make-staging.sh: prints qhhoj-staging.conf, the staging.qhhoj.com server blocks, from qhhoj.conf.
# Staging serves the frontend's `staging` branch against the production api and data. It differs from qhhoj.conf only in:
# no http-level blocks (the upstream and maps come from qhhoj.conf, which must stay installed), its host and certificate,
# its root (/var/www/qhhoj-staging/current, qhhoj-deploy frontend-staging), the headers snippet (production headers plus
# X-Robots-Tag: noindex, nofollow) and /robots.txt (Disallow: /). After editing qhhoj.conf:
#   bash deploy/nginx/make-staging.sh > deploy/nginx/qhhoj-staging.conf   (staging.test.sh fails until it is regenerated)
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
cat <<'HEAD'
# GENERATED by make-staging.sh from qhhoj.conf: do not edit; edit qhhoj.conf and regenerate.
# staging.qhhoj.com: the frontend-v2 `staging` branch against the production api and data; public but never indexed.
# Install as /etc/nginx/conf.d/zz-qhhoj-staging.conf next to qhhoj.conf (whose upstream and maps it uses; the zz- name
# loads it after qhhoj.conf, so it is not the default server for an unknown Host on qhhoj.conf's addresses), plus
# staging-headers.conf as /etc/nginx/snippets/qhhoj-staging-headers.conf (install-host.sh). RUNBOOK "Staging frontend".
HEAD
sed -n '/^server {/,$p' "$here/qhhoj.conf" | sed \
  -e 's#^\(\s*server_name\) oj\.example\.org;.*#\1 staging.qhhoj.com;#' \
  -e 's#/etc/letsencrypt/live/oj\.example\.org/\([a-z]*\.pem\);.*#/etc/letsencrypt/live/staging.qhhoj.com/\1;#' \
  -e 's#^\(\s*root\) /var/www/qhhoj/current;.*#\1 /var/www/qhhoj-staging/current;   \# qhhoj-deploy frontend-staging flips this symlink#' \
  -e 's#/etc/nginx/snippets/qhhoj-security-headers\.conf;#/etc/nginx/snippets/qhhoj-staging-headers.conf;#' \
  -e 's#^\(\s*\)rewrite ^ /api/internal/seo/robots\.txt last;#\1include /etc/nginx/snippets/qhhoj-staging-headers.conf;\n\1default_type text/plain;\n\1return 200 "User-agent: *\\nDisallow: /\\n";#' \
  -e 's#^\(\s*\)\# robots\.txt and the sitemaps are generated by the api (cached there)\.#\1\# Staging is never indexed: robots.txt disallows everything; the sitemaps still come from the api.#'
